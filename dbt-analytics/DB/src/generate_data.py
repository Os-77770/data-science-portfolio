"""
Synthetic telco customer dataset generator.

Produces a realistic, telco-style customer dataset (~8,000 rows) with a
statistically plausible churn signal: customers on month-to-month contracts,
with short tenure, high support-call volume, and frequent late payments churn
far more often than long-tenured customers on annual contracts.

IMPORTANT: This data is 100% SYNTHETIC. It is generated by this script with a
fixed random seed for portfolio / learning purposes only. It does not contain
any real customer information.

Output: data/customers.csv
"""

import numpy as np
import pandas as pd
from pathlib import Path

SEED = 42
N_CUSTOMERS = 8_000

rng = np.random.default_rng(SEED)

CONTRACTS = ["Month-to-month", "One year", "Two year"]
CONTRACT_P = [0.55, 0.27, 0.18]
INTERNET = ["Fiber optic", "DSL", "No"]
INTERNET_P = [0.44, 0.34, 0.22]
PAYMENTS = ["Electronic check", "Mailed check", "Bank transfer (automatic)",
            "Credit card (automatic)"]
PAYMENT_P = [0.34, 0.19, 0.24, 0.23]


def main() -> None:
    n = N_CUSTOMERS

    customer_id = [f"CUST-{i:05d}" for i in range(1, n + 1)]

    contract_type = rng.choice(CONTRACTS, size=n, p=CONTRACT_P)
    internet_service = rng.choice(INTERNET, size=n, p=INTERNET_P)
    payment_method = rng.choice(PAYMENTS, size=n, p=PAYMENT_P)

    # Tenure: mixture - many new customers, tail of loyal ones (1-72 months)
    tenure_months = np.clip(
        np.round(rng.gamma(shape=2.0, scale=15.0, size=n)).astype(int) + 1,
        1, 72,
    )

    # Monthly charges driven mainly by internet service tier
    base = np.select(
        [internet_service == "Fiber optic", internet_service == "DSL"],
        [82.0, 52.0],
        default=24.0,
    )
    monthly_charges = np.round(
        np.clip(rng.normal(base, 13.0), 18.0, 130.0), 2
    )
    total_charges = np.round(monthly_charges * tenure_months *
                             rng.normal(1.0, 0.03, size=n), 2)

    # Behavioural signals
    support_calls = np.clip(rng.poisson(lam=1.6, size=n), 0, 10)
    late_payments = np.clip(rng.poisson(lam=0.9, size=n), 0, 8)

    paperless_billing = rng.choice([0, 1], size=n, p=[0.41, 0.59])
    senior_citizen = rng.choice([0, 1], size=n, p=[0.84, 0.16])

    # ---- Latent churn model (logit) -------------------------------------
    # Coefficients chosen so overall churn lands near ~26%, with strong,
    # interpretable drivers - similar patterns to published telco benchmarks.
    logit = (
        -1.55
        + 1.15 * (contract_type == "Month-to-month")
        + 0.35 * (contract_type == "One year")
        + 0.45 * (internet_service == "Fiber optic")
        + 0.38 * (payment_method == "Electronic check")
        + 0.24 * support_calls
        + 0.33 * late_payments
        + 0.22 * paperless_billing
        - 0.045 * tenure_months
        + 0.004 * (monthly_charges - 65)
    )
    prob = 1.0 / (1.0 + np.exp(-logit))
    churn = (rng.random(n) < prob).astype(int)

    df = pd.DataFrame({
        "customer_id": customer_id,
        "tenure_months": tenure_months,
        "monthly_charges": monthly_charges,
        "total_charges": total_charges,
        "contract_type": contract_type,
        "payment_method": payment_method,
        "internet_service": internet_service,
        "support_calls": support_calls,
        "late_payments": late_payments,
        "paperless_billing": paperless_billing,
        "senior_citizen": senior_citizen,
        "churn": churn,
    })

    out = Path(__file__).resolve().parent.parent / "data" / "customers.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out, index=False)

    print(f"Wrote {out}  ({len(df):,} rows)")
    print(f"Overall churn rate: {df['churn'].mean():.1%}")
    print(df.head())


if __name__ == "__main__":
    main()
